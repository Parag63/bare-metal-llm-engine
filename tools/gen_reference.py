#!/usr/bin/env python3
"""Generate reference ("golden") data for the engine's unit tests.

WHAT THIS IS FOR
----------------
The project's verification standard is that every kernel is checked against an
independent reference implementation. This script produces that reference by running
each operation in PyTorch and writing the inputs together with the expected outputs
into binary files that tests/golden.cpp reads back.

That gives THREE independent implementations of every operation:

    1. PyTorch / NumPy  (this script -> tests/golden/*.bin)
    2. the CPU oracle   (src/cpu_ref/*.cpp)
    3. the CUDA kernel  (kernels/*.cu)

When all three agree, confidence is high. When exactly one disagrees, you know which
one to look at -- which is the real value of having three rather than two. Two
implementations tell you something is wrong; three tell you what.

WHY INPUTS COME FROM NUMPY EVEN ON THE TORCH BACKEND
----------------------------------------------------
Inputs are always generated by NumPy with a fixed seed, and only the *expected
outputs* are computed by the selected backend. So switching backends cannot change
the inputs, which makes the two backends directly comparable and the whole thing
reproducible run to run.

WHY REFERENCES ARE COMPUTED IN FLOAT64
--------------------------------------
The reference should be the most accurate answer available, not merely another
float32 answer. Reductions are done in float64 and the result is cast down to
float32 for storage. This matches the CPU oracle (which accumulates in double) and
means a float32 CUDA kernel is measured against something genuinely better than
itself, rather than against an equally-wrong sibling.

USAGE
-----
    python3 tools/gen_reference.py                  # torch if available, else numpy
    python3 tools/gen_reference.py --backend numpy   # force numpy
    python3 tools/gen_reference.py --out-dir DIR     # default tests/golden
    python3 tools/gen_reference.py --list            # show cases without writing

Output files are generated artifacts and are NOT committed -- see .gitignore. The
script takes about a second, and the build scripts run it for you.
"""

from __future__ import annotations

import argparse
import struct
import sys
from pathlib import Path

import numpy as np

MAGIC = b"ENGREF01"
DTYPE_F32 = 0
SEED = 20260826  # fixed so every run and every machine produces identical inputs


# ---------------------------------------------------------------------------
# Binary writer -- must stay byte-for-byte compatible with tests/golden.cpp
# ---------------------------------------------------------------------------
def write_golden(path: Path, tensors: dict[str, np.ndarray]) -> None:
    """Write a dict of name -> float32 array in the ENGREF01 format."""
    path.parent.mkdir(parents=True, exist_ok=True)

    with path.open("wb") as f:
        f.write(MAGIC)
        f.write(struct.pack("<i", len(tensors)))

        for name, array in tensors.items():
            arr = np.ascontiguousarray(array, dtype=np.float32)
            name_bytes = name.encode("utf-8")

            f.write(struct.pack("<i", len(name_bytes)))
            f.write(name_bytes)
            f.write(struct.pack("<i", DTYPE_F32))
            f.write(struct.pack("<i", arr.ndim))
            for dim in arr.shape:
                f.write(struct.pack("<q", int(dim)))
            f.write(struct.pack("<q", int(arr.nbytes)))
            f.write(arr.tobytes(order="C"))


# ---------------------------------------------------------------------------
# Reference implementations
#
# Each returns float64 results; the writer casts to float32. The numpy and torch
# paths must agree to within float32 precision -- test_golden checks this indirectly
# by comparing the CPU oracle against whichever backend produced the files.
# ---------------------------------------------------------------------------
class NumpyBackend:
    name = "numpy"

    @staticmethod
    def vector_add(a, b):
        return a.astype(np.float64) + b.astype(np.float64)

    @staticmethod
    def reduce_sum(x):
        return np.array([x.astype(np.float64).sum()])

    @staticmethod
    def softmax_rows(x):
        x64 = x.astype(np.float64)
        m = x64.max(axis=-1, keepdims=True)
        e = np.exp(x64 - m)
        return e / e.sum(axis=-1, keepdims=True)

    @staticmethod
    def rmsnorm(x, weight, eps):
        x64 = x.astype(np.float64)
        mean_sq = np.mean(x64 * x64, axis=-1, keepdims=True)
        out = x64 / np.sqrt(mean_sq + eps)
        if weight is not None:
            out = out * weight.astype(np.float64)
        return out

    @staticmethod
    def matmul(a, b):
        return a.astype(np.float64) @ b.astype(np.float64)

    @staticmethod
    def residual_rmsnorm(x, residual, weight, eps):
        x64 = x.astype(np.float64)
        res64 = residual.astype(np.float64)
        sum64 = x64 + res64
        mean_sq = np.mean(sum64 * sum64, axis=-1, keepdims=True)
        norm = sum64 / np.sqrt(mean_sq + eps)
        if weight is not None:
            norm = norm * weight.astype(np.float64)
        return norm, sum64

    @staticmethod
    def rmsnorm_linear(x, weight, W, eps):
        x64 = x.astype(np.float64)
        mean_sq = np.mean(x64 * x64, axis=-1, keepdims=True)
        temp = x64 / np.sqrt(mean_sq + eps)
        if weight is not None:
            temp = temp * weight.astype(np.float64)
        return temp @ W.astype(np.float64)

    @staticmethod
    def gemv(A, x):
        return x.astype(np.float64) @ A.astype(np.float64)

    @staticmethod
    def embedding(table, ids):
        return table[ids.astype(np.int64)].astype(np.float64)

    @staticmethod
    def argmax(x):
        # np.argmax guarantees lowest-index tie-breaking.
        return np.array([int(np.argmax(x.astype(np.float64)))], dtype=np.float64)

    @staticmethod
    def swiglu(gate, up):
        g64 = gate.astype(np.float64)
        u64 = up.astype(np.float64)
        exp_neg = np.exp(-np.abs(g64))
        sigmoid = np.where(g64 >= 0.0, 1.0 / (1.0 + exp_neg), exp_neg / (1.0 + exp_neg))
        return (g64 * sigmoid) * u64

    @staticmethod
    def rope_tables(max_seq_len, head_dim, theta=10000.0):
        half_d = head_dim // 2
        i = np.arange(half_d, dtype=np.float64)
        inv_freq = float(theta) ** (-2.0 * i / float(head_dim))
        pos = np.arange(max_seq_len, dtype=np.float64)[:, None]
        angles = pos * inv_freq[None, :]
        return np.cos(angles), np.sin(angles)

    @staticmethod
    def rope(q, k, cos, sin, convention):
        # q: [s, n_heads, head_dim], k: [s, n_kv_heads, head_dim], cos/sin: [s, half_d]
        def apply_one(x):
            x64 = x.astype(np.float64)
            c = cos[:, None, :]
            s = sin[:, None, :]
            half_d = x64.shape[-1] // 2
            if convention == "rotate_half":
                x0 = x64[..., :half_d]
                x1 = x64[..., half_d:]
                return np.concatenate([x0 * c - x1 * s, x0 * s + x1 * c], axis=-1)
            else:
                x0 = x64[..., 0::2]
                x1 = x64[..., 1::2]
                out = np.empty_like(x64)
                out[..., 0::2] = x0 * c - x1 * s
                out[..., 1::2] = x0 * s + x1 * c
                return out

        return apply_one(q), apply_one(k)

    @staticmethod
    def attention(q, k, v, scale, q_pos_offset, is_causal):
        # q: [s_q, n_heads, head_dim], k/v: [n_kv_heads, s_kv, head_dim]
        q64 = q.astype(np.float64)
        k64 = k.astype(np.float64)
        v64 = v.astype(np.float64)
        s_q, n_heads, head_dim = q64.shape
        n_kv_heads, s_kv, _ = k64.shape
        group = n_heads // n_kv_heads
        out = np.zeros((s_q, n_heads, head_dim), dtype=np.float64)
        lse = np.full((s_q, n_heads), -np.inf, dtype=np.float64)

        k_exp = np.repeat(k64, group, axis=0)  # [n_heads, s_kv, head_dim]
        v_exp = np.repeat(v64, group, axis=0)  # [n_heads, s_kv, head_dim]
        # scores: [n_heads, s_q, s_kv]
        scores = np.einsum("qhd,hkd->hqk", q64, k_exp) * float(scale)

        if is_causal:
            q_idx = np.arange(s_q, dtype=np.int64)[:, None] + q_pos_offset
            k_idx = np.arange(s_kv, dtype=np.int64)[None, :]
            mask = k_idx > q_idx
            scores = np.where(mask[None, :, :], -np.inf, scores)

        for h in range(n_heads):
            for i in range(s_q):
                row = scores[h, i]
                m = np.max(row)
                if not np.isfinite(m) and m < 0.0:
                    continue
                w = np.exp(row - m)
                s_exp = np.sum(w)
                if s_exp == 0.0:
                    continue
                out[i, h] = (w / s_exp) @ v_exp[h]
                lse[i, h] = m + np.log(s_exp)
        return out, lse


class TorchBackend:
    name = "torch"

    def __init__(self):
        import torch  # imported lazily so numpy-only environments still work

        self.torch = torch

    def _t(self, x):
        return self.torch.from_numpy(np.ascontiguousarray(x)).to(self.torch.float64)

    def vector_add(self, a, b):
        return (self._t(a) + self._t(b)).numpy()

    def reduce_sum(self, x):
        return self._t(x).sum().reshape(1).numpy()

    def softmax_rows(self, x):
        # torch.softmax already subtracts the max internally, so this is the same
        # numerically stable formulation the oracle uses.
        return self.torch.softmax(self._t(x), dim=-1).numpy()

    def rmsnorm(self, x, weight, eps):
        t = self.torch
        x64 = self._t(x)
        # The reference LLaMA formulation, written out rather than using
        # torch.nn.RMSNorm so it works on older torch versions and so the maths is
        # visible and checkable against src/cpu_ref/rmsnorm_cpu.cpp.
        out = x64 * t.rsqrt(x64.pow(2).mean(-1, keepdim=True) + eps)
        if weight is not None:
            out = out * self._t(weight)
        return out.numpy()

    def matmul(self, a, b):
        return (self._t(a) @ self._t(b)).numpy()

    def residual_rmsnorm(self, x, residual, weight, eps):
        t = self.torch
        x64 = self._t(x)
        res64 = self._t(residual)
        sum64 = x64 + res64
        norm = sum64 * t.rsqrt(sum64.pow(2).mean(-1, keepdim=True) + eps)
        if weight is not None:
            norm = norm * self._t(weight)
        return norm.numpy(), sum64.numpy()

    def rmsnorm_linear(self, x, weight, W, eps):
        t = self.torch
        x64 = self._t(x)
        temp = x64 * t.rsqrt(x64.pow(2).mean(-1, keepdim=True) + eps)
        if weight is not None:
            temp = temp * self._t(weight)
        return (temp @ self._t(W)).numpy()

    def gemv(self, A, x):
        return (self._t(x) @ self._t(A)).numpy()

    def embedding(self, table, ids):
        idx = self.torch.from_numpy(np.ascontiguousarray(ids, dtype=np.int64))
        return self.torch.nn.functional.embedding(idx, self._t(table)).numpy()

    def argmax(self, x):
        x64 = self._t(x)
        max_val = x64.max()
        first_idx = int((x64 == max_val).nonzero(as_tuple=False)[0, 0].item())
        return np.array([first_idx], dtype=np.float64)

    def swiglu(self, gate, up):
        t = self.torch
        return (t.nn.functional.silu(self._t(gate)) * self._t(up)).numpy()

    def rope(self, q, k, cos, sin, convention):
        t = self.torch

        def apply_one(x):
            xt = self._t(x)
            ct = t.from_numpy(cos.astype(np.float64))[:, None, :]
            st = t.from_numpy(sin.astype(np.float64))[:, None, :]
            half_d = xt.shape[-1] // 2
            if convention == "rotate_half":
                x0 = xt[..., :half_d]
                x1 = xt[..., half_d:]
                return t.cat([x0 * ct - x1 * st, x0 * st + x1 * ct], dim=-1).numpy()
            x0 = xt[..., 0::2]
            x1 = xt[..., 1::2]
            out = t.empty_like(xt)
            out[..., 0::2] = x0 * ct - x1 * st
            out[..., 1::2] = x0 * st + x1 * ct
            return out.numpy()

        return apply_one(q), apply_one(k)

    def attention(self, q, k, v, scale, q_pos_offset, is_causal):
        t = self.torch
        q_t = self._t(q).permute(1, 0, 2)  # [H_q, s_q, D]
        k_t = self._t(k)  # [H_kv, s_kv, D]
        v_t = self._t(v)
        n_heads, s_q, _ = q_t.shape
        n_kv_heads, s_kv, _ = k_t.shape
        group = n_heads // n_kv_heads
        if group > 1:
            k_t = k_t.repeat_interleave(group, dim=0)
            v_t = v_t.repeat_interleave(group, dim=0)
        scores = t.matmul(q_t, k_t.transpose(-2, -1)) * float(scale)
        if is_causal:
            q_idx = t.arange(s_q, dtype=t.int64)[:, None] + q_pos_offset
            k_idx = t.arange(s_kv, dtype=t.int64)[None, :]
            scores = scores.masked_fill((k_idx > q_idx)[None, :, :], float("-inf"))
        m = scores.amax(dim=-1, keepdim=True)
        w = t.exp(scores - m)
        w = t.where(t.isfinite(m), w, t.zeros_like(w))
        s_exp = w.sum(dim=-1, keepdim=True)
        probs = t.where(s_exp > 0, w / s_exp, t.zeros_like(w))
        out = t.matmul(probs, v_t).permute(1, 0, 2)
        lse = (m.squeeze(-1) + t.log(s_exp.squeeze(-1))).permute(1, 0)
        return out.numpy(), lse.numpy()


def select_backend(requested: str):
    if requested == "numpy":
        return NumpyBackend()
    try:
        backend = TorchBackend()
        print(f"backend: torch {backend.torch.__version__}")
        return backend
    except ImportError:
        if requested == "torch":
            print(
                "ERROR: --backend torch requested but PyTorch is not installed.\n"
                "       pip install torch      (or use --backend numpy)",
                file=sys.stderr,
            )
            sys.exit(1)
        print("backend: numpy (PyTorch not installed)")
        print(
            "  NOTE: your project report claims verification against PyTorch.\n"
            "        Install torch on the GPU machine and regenerate before writing\n"
            "        that up, so the claim is literally true."
        )
        return NumpyBackend()


