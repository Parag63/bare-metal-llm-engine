def build_cases(rng, backend):
    """Yield (stem, tensors) pairs."""

    # --- vector_add ---------------------------------------------------------
    for n in VECTOR_ADD_SIZES:
        a = rng.standard_normal(n, dtype=np.float32)
        b = rng.standard_normal(n, dtype=np.float32)
        yield f"vector_add__n{n}", {
            "a": a,
            "b": b,
            "expected": backend.vector_add(a, b),
        }

    # --- reduce_sum ---------------------------------------------------------
    for n in REDUCE_SUM_SIZES:
        # Scaled to keep the float32 sum well inside range while still being large
        # enough that a naive float accumulator would visibly drift -- which is the
        # point being tested.
        x = rng.standard_normal(n, dtype=np.float32)
        yield f"reduce_sum__n{n}", {
            "x": x,
            "expected": backend.reduce_sum(x),
        }

    # --- softmax_rows -------------------------------------------------------
    for rows, cols in SOFTMAX_SHAPES:
        x = rng.standard_normal((rows, cols), dtype=np.float32) * 3.0
        yield f"softmax_rows__{rows}x{cols}", {
            "input": x,
            "expected": backend.softmax_rows(x),
        }

    # The adversarial softmax case. Each row targets a specific failure mode:
    #   row 0: all large negative  -> catches a max initialised to 0.0 instead of -inf
    #   row 1: contains +300       -> catches a missing max subtraction (exp overflows)
    #   row 2: all identical       -> every output must be exactly 1/cols
    #   row 3: one huge, rest tiny -> output is ~one-hot; catches sloppy accumulation
    edge = np.zeros((4, 512), dtype=np.float32)
    edge[0, :] = rng.standard_normal(512, dtype=np.float32) - 50.0
    edge[1, :] = rng.standard_normal(512, dtype=np.float32)
    edge[1, 100] = 300.0
    edge[2, :] = 1.5
    edge[3, :] = -20.0
    edge[3, 7] = 20.0
    yield "softmax_rows__edge", {
        "input": edge,
        "expected": backend.softmax_rows(edge),
    }

    # --- rmsnorm ------------------------------------------------------------
    eps = 1e-5
    for rows, cols, with_weight in RMSNORM_SHAPES:
        x = rng.standard_normal((rows, cols), dtype=np.float32)
        tensors = {"input": x}
        weight = None
        if with_weight:
            # Centred near 1.0, as a trained gain parameter actually is.
            weight = (rng.standard_normal(cols, dtype=np.float32) * 0.1 + 1.0)
            tensors["weight"] = weight
        tensors["expected"] = backend.rmsnorm(x, weight, eps)
        suffix = "w" if with_weight else "now"
        yield f"rmsnorm__{rows}x{cols}_{suffix}", tensors

    # An all-zeros row: without eps this is 0/0. The kernel must return zeros,
    # not NaN.
    zeros = np.zeros((2, 256), dtype=np.float32)
    yield "rmsnorm__zeros", {
        "input": zeros,
        "expected": backend.rmsnorm(zeros, None, eps),
    }

    # --- matmul -------------------------------------------------------------
    for m, n, k in MATMUL_SHAPES:
        # Scaled by 1/sqrt(K) so the magnitude of the result stays near 1 regardless
        # of K. Without this, relative-error tolerances would have to change per
        # shape, which would hide real problems at large K.
        scale = 1.0 / np.sqrt(max(k, 1))
        a = (rng.standard_normal((m, k), dtype=np.float32) * scale).astype(np.float32)
        b = (rng.standard_normal((k, n), dtype=np.float32) * scale).astype(np.float32)
        yield f"matmul__{m}x{n}x{k}", {
            "A": a,
            "B": b,
            "expected": backend.matmul(a, b),
        }

    # --- residual_rmsnorm (Exercise 8) --------------------------------------
    for rows, cols, with_weight in RESIDUAL_RMSNORM_SHAPES:
        x = rng.standard_normal((rows, cols), dtype=np.float32)
        res = rng.standard_normal((rows, cols), dtype=np.float32)
        tensors = {"x": x, "residual": res}
        weight = None
        if with_weight:
            weight = (rng.standard_normal(cols, dtype=np.float32) * 0.1 + 1.0)
            tensors["weight"] = weight
        norm_exp, sum_exp = backend.residual_rmsnorm(x, res, weight, eps)
        tensors["expected"] = norm_exp
        tensors["sum_out"] = sum_exp
        suffix = "w" if with_weight else "now"
        yield f"residual_rmsnorm__{rows}x{cols}_{suffix}", tensors

    # zeros case
    zeros_x = np.zeros((2, 256), dtype=np.float32)
    zeros_res = np.zeros((2, 256), dtype=np.float32)
    norm_exp, sum_exp = backend.residual_rmsnorm(zeros_x, zeros_res, None, eps)
    yield "residual_rmsnorm__zeros", {
        "x": zeros_x,
        "residual": zeros_res,
        "expected": norm_exp,
        "sum_out": sum_exp,
    }

    # --- rmsnorm_linear (Exercise 7) ----------------------------------------
    for m, n, k, with_weight in RMSNORM_LINEAR_SHAPES:
        scale_w = 1.0 / np.sqrt(max(k, 1))
        x = rng.standard_normal((m, k), dtype=np.float32)
        W = (rng.standard_normal((k, n), dtype=np.float32) * scale_w).astype(np.float32)
        tensors = {"input": x, "W": W}
        weight = None
        if with_weight:
            weight = (rng.standard_normal(k, dtype=np.float32) * 0.1 + 1.0)
            tensors["weight"] = weight
        tensors["expected"] = backend.rmsnorm_linear(x, weight, W, eps)
        suffix = "w" if with_weight else "now"
        yield f"rmsnorm_linear__{m}x{n}x{k}_{suffix}", tensors

    # --- gemv ---------------------------------------------------------------
    for n, k in GEMV_SHAPES:
        scale_a = 1.0 / np.sqrt(max(k, 1))
        a = (rng.standard_normal((k, n), dtype=np.float32) * scale_a).astype(np.float32)
        x = rng.standard_normal(k, dtype=np.float32)
        yield f"gemv__{n}x{k}", {
            "A": a,
            "x": x,
            "expected": backend.gemv(a, x),
        }

    # --- gemv_fp16 ----------------------------------------------------------
    for n, k in GEMV_FP16_SHAPES:
        scale_a = 1.0 / np.sqrt(max(k, 1))
        a = (rng.standard_normal((k, n), dtype=np.float32) * scale_a).astype(np.float16)
        x = rng.standard_normal(k, dtype=np.float32).astype(np.float16)
        yield f"gemv_fp16__{n}x{k}", {
            "A": a,
            "x": x,
            "expected": backend.gemv(a, x).astype(np.float16),
        }

    # --- embedding & embedding_fp16 -----------------------------------------
    for v, d, t in EMBEDDING_SHAPES:
        ids = rng.integers(0, v, size=t, dtype=np.int64)
        ids[0] = 0
        if t >= 2:
            ids[1] = v - 1

        table_f32 = rng.standard_normal((v, d), dtype=np.float32)
        yield f"embedding__{t}x{d}_v{v}", {
            "table": table_f32,
            "ids": ids.astype(np.float32),
            "expected": backend.embedding(table_f32, ids),
        }

        table_f16 = rng.standard_normal((v, d), dtype=np.float32).astype(np.float16)
        yield f"embedding_fp16__{t}x{d}_v{v}", {
            "table": table_f16,
            "ids": ids.astype(np.float32),
            "expected": backend.embedding(table_f16, ids).astype(np.float16),
        }

    # --- argmax & argmax_fp16 -----------------------------------------------
    for v in ARGMAX_SIZES:
        logits_f32 = rng.standard_normal(v, dtype=np.float32) * 5.0
        yield f"argmax__v{v}", {
            "logits": logits_f32,
            "expected": backend.argmax(logits_f32),
        }

        logits_f16 = (rng.standard_normal(v, dtype=np.float32) * 5.0).astype(np.float16)
        yield f"argmax_fp16__v{v}", {
            "logits": logits_f16,
            "expected": backend.argmax(logits_f16),
        }

    tie_f32 = rng.uniform(-50.0, -20.0, size=64).astype(np.float32)
    tie_f32[17] = -12.5
    tie_f32[49] = -12.5
    yield "argmax__tie_negative", {
        "logits": tie_f32,
        "expected": backend.argmax(tie_f32),
    }

    tie_f16 = rng.uniform(-50.0, -20.0, size=64).astype(np.float16)
    tie_f16[9] = np.float16(-12.5)
    tie_f16[55] = np.float16(-12.5)
    yield "argmax_fp16__tie_negative", {
        "logits": tie_f16,
        "expected": backend.argmax(tie_f16),
    }

    # --- swiglu & swiglu_fp16 -----------------------------------------------
    for n in SWIGLU_SIZES:
        gate_f32 = rng.standard_normal(n, dtype=np.float32)
        up_f32 = rng.standard_normal(n, dtype=np.float32)
        yield f"swiglu__n{n}", {
            "gate": gate_f32,
            "up": up_f32,
            "expected": backend.swiglu(gate_f32, up_f32),
        }

        gate_f16 = rng.standard_normal(n, dtype=np.float32).astype(np.float16)
        up_f16 = rng.standard_normal(n, dtype=np.float32).astype(np.float16)
        yield f"swiglu_fp16__n{n}", {
            "gate": gate_f16,
            "up": up_f16,
            "expected": backend.swiglu(gate_f16, up_f16).astype(np.float16),
        }

    # --- Module 4: RoPE -----------------------------------------------------
    for name, s, n_heads, n_kv_heads, head_dim, pos_offset, conv in ROPE_CASES:
        q_in = rng.standard_normal((s, n_heads, head_dim), dtype=np.float32).astype(np.float16)
        k_in = rng.standard_normal((s, n_kv_heads, head_dim), dtype=np.float32).astype(np.float16)
        i_idx = np.arange(head_dim // 2, dtype=np.float64)
        inv_freq = 10000.0 ** (-2.0 * i_idx / float(head_dim))
        pos = np.arange(pos_offset, pos_offset + s, dtype=np.float64)[:, None]
        angles = pos * inv_freq[None, :]
        cos_slice = np.cos(angles)
        sin_slice = np.sin(angles)
        q_out, k_out = backend.rope(q_in, k_in, cos_slice, sin_slice, conv)
        yield f"rope__{name}", {
            "q_in": q_in,
            "k_in": k_in,
            "cos": cos_slice,
            "sin": sin_slice,
            "expected": q_out,
            "k_out": k_out,
        }

    # --- Module 4: Attention ------------------------------------------------
    for name, s_q, s_kv, n_heads, n_kv_heads, head_dim, q_pos_offset, is_causal, qk_amp in ATTENTION_CASES:
        q = (rng.standard_normal((s_q, n_heads, head_dim), dtype=np.float32) * qk_amp).astype(np.float16)
        k = (rng.standard_normal((n_kv_heads, s_kv, head_dim), dtype=np.float32) * qk_amp).astype(np.float16)
        v = rng.standard_normal((n_kv_heads, s_kv, head_dim), dtype=np.float32).astype(np.float16)
        scale = 1.0 / np.sqrt(float(head_dim))
        expected, lse = backend.attention(q, k, v, scale, q_pos_offset, is_causal)
        yield f"attention__{name}", {
            "q": q,
            "k": k,
            "v": v,
            "expected": expected,
            "lse": lse,
        }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--backend", choices=["auto", "torch", "numpy"], default="auto")
    parser.add_argument("--out-dir", default=None,
                        help="output directory (default: <repo>/tests/golden)")
    parser.add_argument("--list", action="store_true",
                        help="list the cases that would be written, then exit")
    args = parser.parse_args()

    repo_root = Path(__file__).resolve().parent.parent
    out_dir = Path(args.out_dir) if args.out_dir else repo_root / "tests" / "golden"

    backend = select_backend(args.backend)
    rng = np.random.default_rng(SEED)

    total_bytes = 0
    count = 0

    for stem, tensors in build_cases(rng, backend):
        if args.list:
            shapes = ", ".join(f"{k}{tuple(np.asarray(v).shape)}" for k, v in tensors.items())
            print(f"  {stem}: {shapes}")
            count += 1
            continue

        path = out_dir / f"{stem}.bin"
        write_golden(path, tensors)
        total_bytes += path.stat().st_size
        count += 1

    if args.list:
        print(f"\n{count} case(s)")
        return 0

    print(f"wrote {count} reference file(s) to {out_dir}  "
          f"({total_bytes / 1024 / 1024:.1f} MiB, {backend.name} backend)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
